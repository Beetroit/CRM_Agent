# langgraph_app/services/llm_service.py
import logging
from typing import Optional

from google import genai
from google.genai import types

from langgraph_app.config import LangGraphSettings

logger = logging.getLogger(__name__)


class LLMService:
    def __init__(self, settings: LangGraphSettings):
        self.settings = settings
        # Per user instruction, the client is initialized within the generation method.
        self.client = genai.Client(api_key=self.settings.GOOGLE_API_KEY)

    async def _generate_content(
        self, prompt: str, model_name: str, budget: int = 0
    ) -> Optional[str]:
        """
        Generates content using the Google AI API, following the exact synchronous
        client pattern from the user's example, but run in a separate thread
        to avoid blocking the asyncio event loop.
        """
        logger.info(f"Generating content with model: {model_name}")

        contents = [
            types.Content(role="user", parts=[types.Part.from_text(text=prompt)])
        ]
        # The thinking_config is not available in all versions/models,
        # so it's commented out to prevent potential errors.
        generate_content_config = types.GenerateContentConfig(
            system_instruction="""You respond to users in a friendly and helpful manner. Be concise as you only have 1200 tokens available.
            You can only respond to the user with a single message.Do not use markdown format, respond in paragraphs if you wanna separate text in logical blocks""",
            thinking_config=types.ThinkingConfig(thinking_budget=budget),
            max_output_tokens=1200,
        )
        try:
            response = await self.client.aio.models.generate_content(
                model=model_name,
                contents=contents,
                config=generate_content_config,
            )
            if response.candidates and response.candidates[0].content.parts:
                generated_text = response.candidates[0].content.parts[0].text
                logger.info(
                    f"Successfully generated content: '{generated_text[:100]}...'"
                )
                return generated_text.strip()
            else:
                logger.warning("No content was generated by the model.")
                return None
        except Exception as e:
            # Catching broad exception to log any issue from the API call
            logger.error(f"An error occurred while generating content: {e}")
            return None

    async def classify_intent(self, text: str) -> str:
        """Classifies the user's intent using a dedicated LLM."""
        logger.info(f"Classifying intent for: '{text}'")
        allowed_intents = ", ".join(self.settings.ALLOWED_INTENTS)
        prompt = (
            f"Based on the following user message, classify the intent into one of the following categories: "
            f"[{allowed_intents}].\n\n"
            f"User Message: '{text}'\n\n"
            f"Respond with only the intent category name and nothing else."
        )

        intent = await self._generate_content(prompt, self.settings.INTENT_MODEL_NAME)

        if intent and intent.lower() in self.settings.ALLOWED_INTENTS:
            logger.info(f"LLM classified intent as: '{intent.lower()}'")
            return intent.lower()
        else:
            logger.warning(
                f"LLM returned an invalid or empty intent: '{intent}'. Defaulting to 'statement'."
            )
            return "statement"

    async def generate_response(
        self, intent: str, text: str, context: str = None
    ) -> str:
        """Generates a response based on the intent, user text, and context."""
        logger.info(f"Generating response for intent '{intent}' with text: {text}")

        prompt = f"Intent: {intent}\n"
        if context:
            prompt += f"Context: {context}\n"
        prompt += f"User message: {text}\n\n"
        prompt += "Generate a suitable response:"

        response = await self._generate_content(
            prompt, self.settings.RESPONSE_MODEL_NAME, budget=8192
        )

        if response:
            logger.info(f"LLM generated response: {response}")
            return response
        else:
            logger.error("Failed to generate a response from the LLM.")
            return "I'm sorry, I couldn't process your request at the moment."
